def normalize_country(raw_name: str) -> str | None:
    """Return ISO alpha-3 for a raw country name string, or None if unknown."""
    if not raw_name or str(raw_name).strip() in ("", "nan"):
        return None
    raw = str(raw_name).strip()
    # Direct lookup
    if raw in COUNTRY_MAP:
        return COUNTRY_MAP[raw]
    # Case-insensitive lookup
    for k, v in COUNTRY_MAP.items():
        if k.lower() == raw.lower():
            return v
    return None
